# нормализация «ё», регистр
_NORM = str.maketrans({"ё": "е", "Ё": "Е"})

# Слова, которые похожи на название региона, но в постах канала означают район
# Петербурга или маленький город. Убираем их, если полное название региона не названо.
_EXPLICIT = {
    "Московская область": r"московск\w*\s+област|\bподмосков",
    "Кировская область": r"кировск\w*\s+област",
    "Приморский край": r"приморск\w*\s+кра",
}
_AMBIGUOUS = (
    (r"московск\w*\s+(?:район\w*|славянк\w*|ворот\w*|проспект\w*|шоссе\w*)",
     "Московская область"),
    (r"\bмосковск(?:ий|ого|ому|им|ом)\b(?!\s+регион)", "Московская область"),
    (r"кировск\w*\s+район\w*", "Кировская область"),
    (r"\bкировск(?:ий|ого|ому|им|ом)\b", "Кировская область"),
    (r"\bкировск(?:е|а|у|ом)?\b", "Кировская область"),
    (r"приморск\w*\s+район\w*", "Приморский край"),
    (r"\bприморск(?:ий|ого|ому|им|ом)\b(?!\s+кра)", "Приморский край"),
    (r"\bприморск(?:е|а|у|ом)?\b", "Приморский край"),
)

# допустимые падежные окончания после основы
_ENDINGS = {
    "", "а", "я", "у", "ю", "е", "и", "ы", "ь", "й",
    "ой", "ый", "ий", "ая", "яя", "ое", "ее", "ие", "ые",
    "ого", "его", "ому", "ему", "ым", "им", "ом", "ем",
    "ах", "ях", "ам", "ям", "ов", "ев", "ия", "ии", "ию", "ией",
    "ской", "скую", "ский", "ском", "ского", "ская", "ским", "ских",
    "кой", "кую", "кая", "ких",
    "ую", "ею", "ья", "ье", "ью",
}


def normalize(text: str) -> str:
    return text.translate(_NORM).lower().replace("—", "-").replace("–", "-")


def _sanitize(norm: str) -> str:
    """Убирает «Московский район», «Кировский район», «Приморск» и подобные
    двусмысленности, если рядом нет полного названия региона."""
    for pattern, region in _AMBIGUOUS:
        if re.search(_EXPLICIT[region], norm):
            continue
        norm = re.sub(pattern, " ", norm)
    return norm


class RegionIndex:
    def __init__(self, geo_path: Path = GEO_PATH):
        raw = json.loads(geo_path.read_text(encoding="utf-8"))
        self.features = raw["features"]
        self.meta: dict[str, dict] = {}
        for f in self.features:
            props = f["properties"]
            name = props["name"]
            self.meta[name] = {
                "name": name,
                "fo": props.get("fo", ""),
                "code": props.get("code", ""),
                "label": short_label(name),
                "capital": props.get("capital", ""),
            }
        self.aliases = {k: [normalize(a) for a in v] for k, v in ALIASES.items()}

    def find(self, text: str) -> list[str]:
        """Канонические названия регионов, упомянутых в тексте (по порядку появления)."""
        norm = _sanitize(normalize(text))
        words = re.findall(r"[а-яa-z0-9]+", norm)
        found: dict[str, int] = {}
        for region, stems in self.aliases.items():
            for stem in stems:
                if " " in stem:
                    pos = norm.find(stem)
                    if pos >= 0:
                        found.setdefault(region, pos)
                        break
                    continue
                hit = None
                for idx, w in enumerate(words):
                    if not w.startswith(stem):
                        continue
                    rest = w[len(stem):]
                    if rest in _ENDINGS:
                        hit = idx
                        break
                if hit is not None:
                    found.setdefault(region, hit)
                    break
        # города — только как дополнение
        for city, region in CITY_TO_REGION.items():
            if region in found:
                continue
            for w in words:
                if w.startswith(city) and w[len(city):] in _ENDINGS:
                    if region in self.meta:
                        found[region] = len(words)
                    break

        # устойчивые обороты, которые не ловятся по названию региона
        if re.search(r"москв\w*\s+и\s+област", norm) and "Московская область" in self.meta:
            found.setdefault("Московская область", len(words))
        if re.search(r"москв\w*\s+и\s+московск", norm) and "Московская область" in self.meta:
            found.setdefault("Московская область", len(words))

        return [r for r, _ in sorted(found.items(), key=lambda kv: kv[1])]

    def is_european(self, region: str) -> bool:
        return self.meta.get(region, {}).get("fo") in EUROPE_FOS


def short_label(name: str) -> str:
    short_names = {"Удмуртская Республика": "Удмуртия"}
    if name in short_names:
        return short_names[name]
    s = name
    for prefix in ("Республика ", "Удмуртская ", "Чувашская ", "Кабардино-Балкарская ",
                   "Карачаево-Черкесская ", "Чеченская ", "Донецкая Народная ",
                   "Луганская Народная "):
        if s.startswith(prefix):
            s = s[len(prefix):]
    s = s.replace("Республика ", "")
    s = re.sub(r"\s*\(.*?\)", "", s)
    s = s.replace("автономный округ — Югра", "АО").replace("автономный округ", "АО")
    s = s.replace("Санкт-Петербург", "СПб").replace("Республика ", "")
    s = s.replace(" область", " обл.").replace(" край", " кр.")
    if s.endswith(" обл.") or s.endswith(" кр."):
        return s
    return s
